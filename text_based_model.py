def predict_text(text, verbose=True):
    inputs = tokenizer(
        text, padding=True, truncation=True,
        max_length=MAX_LEN, return_tensors="pt"
    ).to(device)

    with torch.no_grad():
        outputs = model(**inputs)
        logits  = outputs.logits
        pred    = torch.argmax(logits, dim=1).item()
        probs   = torch.softmax(logits, dim=1)[0]

    label_map = {0: "Non-ASD", 1: "ASD"}
    if verbose:
        print(f"\nText       : {text}")
        print(f"Prediction : {label_map[pred]}")
        print(f"Confidence : {probs[pred].item():.4f}")
        print(f"  Non-ASD  : {probs[0].item():.4f}  |  ASD : {probs[1].item():.4f}")

    return pred, probs.cpu().numpy()

