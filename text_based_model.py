class EnhancedDistilBertClassifier(nn.Module):
    def __init__(self, num_labels=2, dropout_rate=0.3, label_smoothing=0.15):
        super().__init__()
        self.distilbert = DistilBertModel.from_pretrained(
            "distilbert-base-uncased",
            attn_implementation="eager"
        )
        hidden = self.distilbert.config.hidden_size  # 768

        # Unfreeze last 4 layers for better learning
        for name, p in self.distilbert.named_parameters():
            if any(f"transformer.layer.{i}" in name for i in [2, 3, 4, 5]):
                p.requires_grad = True
            else:
                p.requires_grad = False

        # Simplified head with gradient clipping friendly architecture
        self.pre_classifier = nn.Linear(hidden, hidden)
        self.layer_norm     = nn.LayerNorm(hidden)
        self.dropout1       = nn.Dropout(dropout_rate)
        self.intermediate   = nn.Linear(hidden, 256)
        self.activation     = nn.GELU()
        self.dropout2       = nn.Dropout(dropout_rate)
        self.classifier     = nn.Linear(256, num_labels)
        self.num_labels      = num_labels
        self.label_smoothing = label_smoothing

    def forward(self, input_ids=None, attention_mask=None,
                labels=None, output_attentions=False):
        out = self.distilbert(
            input_ids=input_ids,
            attention_mask=attention_mask,
            output_attentions=output_attentions
        )
        x = out.last_hidden_state[:, 0]          # CLS
        x = self.activation(self.layer_norm(self.pre_classifier(x)))
        x = self.dropout1(x)
        x = self.activation(self.intermediate(x))
        x = self.dropout2(x)
        logits = self.classifier(x)

        loss = None
        if labels is not None:
            loss = nn.CrossEntropyLoss(
                label_smoothing=self.label_smoothing
            )(logits, labels)

        return SequenceClassifierOutput(
            loss=loss, logits=logits,
            hidden_states=out.hidden_states,
            attentions=out.attentions
        )

