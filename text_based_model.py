def plot_attention_heatmap(text, layer=-1, head=0, save_path="attention_heatmap.png"):
    """
    Plot token-to-token attention weights for a given input text.
    layer : transformer layer index (-1 = last layer)
    head  : attention head index (0–5 for DistilBERT)
    """
    inputs = tokenizer(
        text,
        return_tensors="pt",
        truncation=True,
        max_length=MAX_LEN
    ).to(device)

    with torch.no_grad():
        outputs = model(**inputs, output_attentions=True)

    attentions = outputs.attentions
    if attentions is None:
        print("ERROR: attentions is None. Ensure attn_implementation='eager'.")
        return

