# =============================
def predict_ensemble(text, verbose=True):
    _, bert_p = predict_text(text, verbose=False)
    lr_p      = tfidf_pipeline.predict_proba([text])[0]

    combined  = BERT_WEIGHT * bert_p + LR_WEIGHT * lr_p
    pred      = np.argmax(combined)
    label_map = {0: "Non-ASD", 1: "ASD"}

    if verbose:
        print(f"\nText              : {text}")
        print(f"Ensemble Result   : {label_map[pred]}")
        print(f"  Non-ASD prob    : {combined[0]:.4f}")
        print(f"  ASD prob        : {combined[1]:.4f}")
        print(f"  (BERT {BERT_WEIGHT} + LR {LR_WEIGHT} weighted)")

    return label_map[pred], combined

